-- ============================================================
-- V128: 事件「预期完成时间」
-- 背景：创建事件时需要登记预期完成时间，作为闭环处置的时限与跟进依据；
--       列表/详情展示该时间，便于判断是否临近或超期。
-- 本迁移：biz_event 增加 expected_completion_time 列
--         （可空，历史数据不受影响；不设默认值，避免给存量事件伪造时限）
-- 说明：Flyway 保证只执行一次
-- ============================================================

ALTER TABLE `biz_event`
  ADD COLUMN `expected_completion_time` datetime NULL COMMENT '预期完成时间（创建事件时登记，可空）' AFTER `occurred_at`;
