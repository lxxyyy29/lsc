def TABLE(headers, rows, widths=None, hdr_fill='2E75B6'):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.text = h
        for pr in cell.paragraphs:
            for r in pr.runs:
                r.bold = True
                r.font.size = Pt(9)
                r.font.name = '微软雅黑'
                r.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
                r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        shd = cell._tc.get_or_add_tcPr()
        shd.append(shd.makeelement(qn('w:shd'), {qn('w:fill'): hdr_fill}))
    for row in rows:
        cells = t.add_row().cells
        for j, v in enumerate(row):
            cells[j].text = str(v)
            for pr in cells[j].paragraphs:
                for r in pr.runs:
                    r.font.size = Pt(9)
                    r.font.name = '微软雅黑'
                    r.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Cm(w)
    return t


